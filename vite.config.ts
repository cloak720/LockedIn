import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/*
 * Content Security Policy.
 *
 * 1. A <meta> CSP is injected into index.html for every production build
 *    (works on any host, and for `npm run preview`).
 * 2. A stricter HTTP-header CSP is written to dist/_headers (Netlify / Cloudflare
 *    Pages). When LOCKEDIN_ORIGIN is set (e.g. https://my-site.netlify.app), scripts,
 *    styles and fonts are restricted to `${origin}/assets/` only, so even code the
 *    HOST injects into the page from its own domain (e.g. /.netlify/scripts/...)
 *    is refused. Browsers enforce both policies, so the strictest wins.
 */
const AI_APIS = 'https://generativelanguage.googleapis.com https://api.groq.com https://openrouter.ai';

export const META_CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self' ${AI_APIS}`,
  "manifest-src 'self'",
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

function headerCsp(origin: string | undefined) {
  const assets = origin ? `${origin.replace(/\/+$/, '')}/assets/` : "'self'";
  return [
    "default-src 'none'",
    `script-src ${assets}`,
    `style-src ${assets}`,
    `font-src ${assets} data:`,
    "img-src 'self' data: blob:",
    `connect-src 'self' ${AI_APIS}`,
    "manifest-src 'self'",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

function securityPlugin(): Plugin {
  const origin = process.env.LOCKEDIN_ORIGIN?.trim() || undefined;
  if (origin && !/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(origin)) {
    throw new Error(`LOCKEDIN_ORIGIN must look like https://example.com (got "${origin}")`);
  }
  return {
    name: 'lockedin-security',
    apply: 'build',
    transformIndexHtml(html) {
      return html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    <meta http-equiv="Content-Security-Policy" content="${META_CSP}" />`);
    },
    generateBundle() {
      const headers = `# Generated by vite.config.ts. Do not edit dist/_headers by hand.
# Security headers for Netlify / Cloudflare Pages.${origin ? `\n# Scripts/styles locked to ${origin}/assets/` : '\n# Set LOCKEDIN_ORIGIN at build time to lock scripts/styles to /assets/.'}
/*
  Content-Security-Policy: ${headerCsp(origin)}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  X-Robots-Tag: noindex

/sw.js
  Cache-Control: no-cache

/manifest.webmanifest
  Content-Type: application/manifest+json; charset=utf-8
  Cache-Control: no-cache
`;
      this.emitFile({ type: 'asset', fileName: '_headers', source: headers });
    },
  };
}

// Relative base so the build works from any folder / GitHub Pages / Capacitor / Tauri.
export default defineConfig({
  plugins: [react(), securityPlugin()],
  base: './',
  // localhost only. Use `npm run dev -- --host` to test on a phone on your own Wi-Fi.
  server: { port: 5173, host: 'localhost' },
  preview: { port: 4173, host: 'localhost' },
  build: { sourcemap: false },
});
